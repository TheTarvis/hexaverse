import { fireEvent, render, screen, within } from '@testing-library/react'
import { describe, expect, it } from 'vitest'
import { SystemStoryboard } from './SystemStoryboard'

const click = (id: string) => fireEvent.click(screen.getByTestId(id))

describe('first flight design storyboard', () => {
  it('opens as a command view with optional review controls', () => {
    render(<SystemStoryboard mode="journey" />)
    expect(screen.queryByRole('complementary', { name: 'Storyboard controls' })).not.toBeInTheDocument()
    expect(screen.getByText('COMMAND NETWORK / 1 FLEET · 1 SHIP')).toBeVisible()
    click('toggle-review')
    expect(screen.getByRole('complementary', { name: 'Storyboard controls' })).toBeVisible()
    fireEvent.keyDown(screen.getByTestId('toggle-review'), { key: 'Escape' })
    expect(screen.getByTestId('toggle-review')).toHaveAttribute('aria-expanded', 'false')
  })

  it('wakes on the selected fleet and confirms movement and mining only on completion', () => {
    render(<SystemStoryboard mode="journey" />)
    click('toggle-review')
    expect(screen.getByTestId('previous-scene')).toBeDisabled()
    expect(screen.getByTestId('active-fleet')).toHaveAccessibleName('Nyxiour, selected fleet')
    expect(screen.getByTestId('system-camera')).toHaveAttribute('data-focus', 'fleet')
    expect(screen.getByTestId('tutorial-prompt')).toHaveTextContent('Wakey wakey. You’re online.')
    expect(screen.queryByText('Find my fleet')).not.toBeInTheDocument()
    expect(screen.getByTestId('planet-Nereid')).toBeDisabled()
    click('preview-action')
    expect(screen.getByTestId('intro-prompt')).toHaveTextContent('Open the Objects panel')
    click('intro-action')
    expect(screen.getByTestId('intro-prompt')).toHaveTextContent('home port')
    click('intro-action')
    click('intro-action')
    expect(screen.getByTestId('intro-prompt')).toHaveTextContent('Waiting for the scan report')
    click('intro-action')
    click('index-Nereid')
    expect(screen.getByTestId('world-locator')).toHaveTextContent('Nereid')
    expect(screen.getByTestId('system-camera')).toHaveAttribute('data-focus', 'system')
    expect(screen.getByTestId('planet-Vesper')).toBeDisabled()
    expect(screen.getByTestId('planet-Nereid')).toHaveAttribute('aria-pressed', 'true')
    expect(screen.queryByRole('complementary', { name: 'Contextual command panel' })).not.toBeInTheDocument()
    click('details-plot')
    const panel = screen.getByRole('complementary', { name: 'Contextual command panel' })
    expect(screen.getByTestId('story-command-rail')).toContainElement(panel)
    expect(within(panel).getByText('4.8 t')).toBeInTheDocument()
    expect(within(panel).getByText('2m 14s')).toBeInTheDocument()
    click('cancel-course')
    expect(within(panel).queryByText('Fuel required')).not.toBeInTheDocument()
    click('preview-action')
    click('preview-action')
    expect(within(panel).getByText('FLIGHT IN PROGRESS')).toBeInTheDocument()
    expect(screen.queryByTestId('world-locator')).not.toBeInTheDocument()
    expect(screen.getByTestId('planet-Nereid')).toBeDisabled()
    expect(screen.getByTestId('motor-check')).toHaveAttribute('data-state', 'pending')
    click('preview-action')
    expect(within(panel).getByText('Docked at Nereid')).toBeInTheDocument()
    expect(within(panel).getByText('66.5 t')).toBeInTheDocument()
    expect(screen.getByTestId('motor-check')).toHaveAttribute('data-state', 'complete')
    expect(screen.getByTestId('mining-check')).toHaveAttribute('data-state', 'pending')
    expect(screen.getByTestId('preview-action')).toHaveTextContent('Mine 10 t of volatiles')
    click('preview-action')
    expect(screen.getByTestId('sample-cargo')).toHaveTextContent('0 t')
    expect(screen.getByTestId('mining-check')).toHaveAttribute('data-state', 'pending')
    click('preview-action')
    expect(screen.getByTestId('sample-cargo')).toHaveTextContent('10 t')
    expect(screen.getByTestId('mining-check')).toHaveAttribute('data-state', 'complete')
    expect(screen.getByTestId('fuel-check')).toHaveAttribute('data-state', 'pending')
    expect(within(panel).getByText('66.5 t')).toBeInTheDocument()
    click('preview-action')
    expect(within(panel).getByText('61.7 t')).toBeInTheDocument()
    click('cancel-course')
    expect(screen.getByTestId('sample-cargo')).toHaveTextContent('10 t')
    expect(within(panel).getByText('66.5 t')).toBeInTheDocument()
    click('preview-action')
    click('preview-action')
    expect(within(panel).getByText('FLIGHT IN PROGRESS')).toBeInTheDocument()
    expect(screen.getByTestId('story-credits')).toHaveTextContent('1,000')
    click('preview-action')
    expect(within(panel).getByText('Docked at Home Station')).toBeInTheDocument()
    expect(screen.getByTestId('preview-action')).toHaveTextContent('Sell 10 t for 100 credits')
    click('preview-action')
    expect(screen.getByTestId('sample-cargo')).toHaveTextContent('0 t')
    expect(screen.getByTestId('story-credits')).toHaveTextContent('1,100')
    expectCanonicalFreeHold(138.3, '138\u2009t')
    expect(screen.getByTestId('fuel-check')).toHaveAttribute('data-state', 'pending')
    click('preview-action')
    expect(screen.getByTestId('story-credits')).toHaveTextContent('1,000')
    expect(within(panel).getByText('71.7 t')).toBeInTheDocument()
    expectCanonicalFreeHold(128.3, '128\u2009t')
    expect(screen.getByTestId('fuel-check')).toHaveAttribute('data-state', 'complete')
    expect(screen.getByTestId('preview-action')).toBeDisabled()
    expect(screen.getByTestId('next-scene')).toBeDisabled()
    click('restart-storyboard')
    expect(screen.getByTestId('preview-action')).toHaveTextContent('Begin systems check')
    expect(screen.getByTestId('motor-check')).toHaveAttribute('data-state', 'pending')
    expect(screen.getByTestId('system-camera')).toHaveAttribute('data-focus', 'fleet')
    expect(screen.getByTestId('fuel-check')).toHaveAttribute('data-state', 'pending')
  })

  it('keeps scene review checks separate and clears them on reset', () => {
    render(<SystemStoryboard mode="journey" />)
    click('toggle-review')
    click('review-check-0')
    click('scene-1')
    expect(screen.getByTestId('review-check-0')).not.toBeChecked()
    click('scene-0')
    expect(screen.getByTestId('review-check-0')).toBeChecked()
    click('restart-storyboard')
    expect(screen.getByTestId('review-check-0')).not.toBeChecked()
  })

  it('compares HUD density and recovers from loading, empty, and error states', () => {
    render(<SystemStoryboard mode="hud" />)
    click('density-rich')
    expect(screen.getByRole('complementary', { name: 'System objects' })).toBeInTheDocument()
    for (const state of ['loading', 'empty', 'error']) {
      click(`state-${state}`)
      expect(screen.queryByTestId('preview-action')).not.toBeInTheDocument()
      expect(screen.getByTestId('planet-Nereid')).toBeDisabled()
      click('state-recover')
      expect(screen.getByTestId('preview-action')).toBeInTheDocument()
    }
    click('toggle-labels')
    expect(screen.getByTestId('toggle-labels')).toHaveAttribute('aria-pressed', 'false')
    click('restart-storyboard')
    expect(screen.getByTestId('density-quiet')).toHaveAttribute('aria-pressed', 'true')
  })
})


it('restores coherent economy snapshots when reviewing scenes out of order', () => {
  render(<SystemStoryboard mode="journey" />)
  click('toggle-review')
  click('scene-12')
  expect(screen.getByTestId('fuel-check')).toHaveAttribute('data-state', 'complete')
  click('scene-7')
  expect(screen.getByTestId('sample-cargo')).toHaveTextContent('10 t')
  expect(screen.getByTestId('story-credits')).toHaveTextContent('1,000')
  expect(screen.getByTestId('fuel-check')).toHaveAttribute('data-state', 'pending')
  click('scene-11')
  expect(screen.getByTestId('sample-cargo')).toHaveTextContent('0 t')
  expect(screen.getByTestId('story-credits')).toHaveTextContent('1,100')
})


it('locates off-screen objects without plotting or changing the active fleet', () => {
  render(<SystemStoryboard mode="journey" />)
  click('preview-action')
  click('intro-action')
  click('intro-action')
  click('intro-action')
  click('intro-action')
  click('index-Nereid')
  click('simulate-offscreen')
  expect(screen.queryByTestId('world-locator')).not.toBeInTheDocument()
  expect(screen.getByTestId('edge-locator')).toHaveTextContent('Nereid')
  click('edge-locator')
  expect(screen.getByTestId('system-camera')).toHaveAttribute('data-focus', 'object')
  expect(screen.getByTestId('active-fleet')).toHaveAccessibleName('Nyxiour, selected fleet')
  expect(screen.getByTestId('preview-action')).toHaveTextContent('Plot course')
  click('system-index-toggle')
  click('details-plot')
  expect(screen.getByTestId('preview-action')).toHaveTextContent('Engage drive')
})


it('dismisses the locator on close, Escape, course preview and burn commitment', () => {
  render(<SystemStoryboard mode="journey" />)
  click('preview-action')
  click('intro-action')
  click('intro-action')
  click('intro-action')
  click('intro-action')
  click('index-Nereid')
  click('locator-close')
  expect(screen.queryByTestId('world-locator')).not.toBeInTheDocument()
  click('index-Nereid')
  fireEvent.keyDown(screen.getByTestId('locator-close'), { key: 'Escape' })
  expect(screen.queryByTestId('world-locator')).not.toBeInTheDocument()
  click('index-Nereid')
  click('details-plot')
  expect(screen.queryByTestId('world-locator')).not.toBeInTheDocument()
  click('preview-action')
  expect(screen.queryByTestId('world-locator')).not.toBeInTheDocument()
  expect(screen.getByTestId('preview-action')).toHaveTextContent('Simulate arrival')
})

// Archive compatibility amendment: covered tonnage uses Figure metadata and
// canonical shared precision. Keep the surrounding transaction assertions intact.
function expectCanonicalFreeHold(raw: number, text: string) {
  const host = screen.getByTestId('free-hold')
  const figures = host.querySelectorAll('[data-unit="tons"]')
  expect(figures).toHaveLength(2)
  expect(Number(figures[0].getAttribute('data-raw'))).toBeCloseTo(raw, 10)
  expect(figures[0].textContent).toBe(text)
  expect(figures[1]).toHaveAttribute('data-raw', '200')
  expect(figures[1].textContent).toBe('200\u2009t')
  expect(host.textContent).toBe(`${text} / 200\u2009t`)
}
