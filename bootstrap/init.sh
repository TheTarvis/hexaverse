#!/usr/bin/env bash
#
# Substitutes {{PLACEHOLDER}} tokens across the repo using values from
# bootstrap/config.env, and writes frontend/.env.local with Firebase config.
#
# Run from the repo root:    bash bootstrap/init.sh
# Or from anywhere:          bash /path/to/repo/bootstrap/init.sh
#
# Re-runnable: substitutions are idempotent (placeholders are gone after first
# run, so nothing to substitute on subsequent runs). To template a new project,
# fork the original skeleton repo — don't try to "un-substitute" an in-place tree.

set -euo pipefail

# Resolve repo root from script location (works regardless of cwd).
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$REPO_ROOT"

CONFIG="${1:-bootstrap/config.env}"
if [[ ! -f "$CONFIG" ]]; then
  echo "Config file not found: $CONFIG" >&2
  echo "Copy bootstrap/config.example.env to bootstrap/config.env and fill it in." >&2
  exit 1
fi

# Source config — `set -a` exports every assignment so they're visible to subshells.
set -a
# shellcheck disable=SC1090
source "$CONFIG"
set +a

# Required substitution placeholders. Order matters: longer/more-specific keys
# would shadow shorter ones if both appeared in the same string, but the
# placeholder format ({{KEY}}) makes that impossible — they can't overlap.
SUBST_KEYS=(
  PROJECT_SLUG
  PROJECT_NAME
  GCP_PROJECT_DEV
  GCP_PROJECT_PROD
  PROD_DOMAIN
  DEV_DOMAIN
)

# Validate required values up front.
missing=()
for key in "${SUBST_KEYS[@]}"; do
  if [[ -z "${!key:-}" ]]; then
    missing+=("$key")
  fi
done
if (( ${#missing[@]} > 0 )); then
  echo "Missing required values in $CONFIG:" >&2
  for k in "${missing[@]}"; do echo "  $k" >&2; done
  exit 1
fi

# Build a NUL-delimited file list with `find`. We allowlist file types (no
# binaries) and skip generated/tooling directories.
collect_files() {
  find . \
    \( -path './node_modules' -o -path './.git' -o -path './.next' -o -path './.idea' -o -path './.venv' -o -path './bootstrap' \) -prune \
    -o -type f \( \
         -name '*.go' -o -name '*.ts' -o -name '*.tsx' -o -name '*.js' -o -name '*.mjs' \
      -o -name '*.json' -o -name '*.tf' -o -name '*.yml' -o -name '*.yaml' \
      -o -name '*.xml' \
      -o -name '*.mod' -o -name '*.sum' -o -name 'Makefile' -o -name '*.sh' \
      -o -name '*.md' -o -name '*.example' \
      -o -name '*.toml' -o -name '*.py' -o -name 'Dockerfile' \
    \) -print0
}

# In-place sed flag — BSD sed (macOS) needs `-i ''`, GNU sed wants `-i`.
sed_inplace() {
  if sed --version >/dev/null 2>&1; then
    sed -i "$@"
  else
    sed -i '' "$@"
  fi
}

# Run substitutions.
echo "Substituting placeholders across the repo..."
sed_args=()
for key in "${SUBST_KEYS[@]}"; do
  val="${!key}"
  # Escape sed delimiters in the value. Use | as delimiter; values are short
  # config strings, unlikely to contain |.
  esc_val="${val//|/\\|}"
  sed_args+=(-e "s|{{$key}}|$esc_val|g")
  echo "  {{$key}} → $val"
done

# shellcheck disable=SC2046
collect_files | xargs -0 -n 50 -- bash -c '
  if sed --version >/dev/null 2>&1; then
    sed -i "$@"
  else
    sed -i "" "$@"
  fi
' _ "${sed_args[@]}"

# Write frontend/.env.local with Firebase config + local API URL.
# Uses the FIREBASE_*_DEV values from config.env (the prod set is kept around
# for pasting into Vercel later, not for local dev).
if [[ -d frontend ]]; then
  echo "Writing frontend/.env.local..."
  cat > frontend/.env.local <<EOF
# Generated by bootstrap/init.sh — gitignored, safe to edit by hand.
NEXT_PUBLIC_API_URL=${API_URL_LOCAL:-http://localhost:9010}
NEXT_PUBLIC_CLAUDE_AGENT_URL=http://localhost:8100

NEXT_PUBLIC_FIREBASE_API_KEY=${FIREBASE_API_KEY_DEV:-}
NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN=${FIREBASE_AUTH_DOMAIN_DEV:-}
NEXT_PUBLIC_FIREBASE_PROJECT_ID=${FIREBASE_PROJECT_ID_DEV:-}
NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET=${FIREBASE_STORAGE_BUCKET_DEV:-}
NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID=${FIREBASE_MESSAGING_SENDER_ID_DEV:-}
NEXT_PUBLIC_FIREBASE_APP_ID=${FIREBASE_APP_ID_DEV:-}
EOF
fi

# Create backend/.env.local from the (now-substituted) example, if absent.
# The backend refuses to start without FIREBASE_PROJECT_ID, and nothing else
# generates this file.
if [[ -d backend && ! -f backend/.env.local ]]; then
  echo "Writing backend/.env.local from backend/.env.local.example..."
  cp backend/.env.local.example backend/.env.local
fi

# Same for the agent: claude-agent/.env from its (substituted) example.
# ANTHROPIC_API_KEY must still be filled in by hand before /chat works.
if [[ -d claude-agent && ! -f claude-agent/.env ]]; then
  echo "Writing claude-agent/.env from claude-agent/.env.example (fill in ANTHROPIC_API_KEY)..."
  cp claude-agent/.env.example claude-agent/.env
fi

echo
echo "Done. Next steps:"
echo "  cd backend && go mod tidy && go build ./..."
echo "  cd frontend     && npm install && npm run dev"
