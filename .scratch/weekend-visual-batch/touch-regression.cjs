// Isolated browser-generated touch input. No Auth, API reads or game mutations.
const assert = require('node:assert/strict')
const { chromium, webkit } = require('../../frontend/node_modules/playwright')
const fs = require('node:fs')
const path = require('node:path')
const output = process.env.TOUCH_QA_OUTPUT || '/tmp/hexaverse-touch-qa'
fs.mkdirSync(output, { recursive: true })
const url = 'http://127.0.0.1:20203/iframe.html?id=hud-mobile-system--touch-map&viewMode=story'
;(async () => {
 const browser = await chromium.launch({ headless: true })
 try {
 const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
 const page = await context.newPage()
 await page.goto(url)
 await page.getByTestId('space-canvas-region').waitFor()
 await page.waitForFunction(() => !!document.querySelector('[data-testid="space-camera-controls"]'))
 const region = page.getByTestId('space-canvas-region')
 const camera = async () => JSON.parse(await region.getAttribute('data-camera'))
 const session = await context.newCDPSession(page)
 const contact = (id, x, y) => ({ id, x, y, radiusX: 4, radiusY: 4, force: 1 })
 const touch = (type, points) => session.send('Input.dispatchTouchEvent', { type, touchPoints: points })
 const before = await camera()
 await touch('touchStart', [contact(1, 190, 310)])
 await touch('touchMove', [contact(1, 245, 345)])
 await touch('touchEnd', [])
 assert.notDeepEqual((await camera()).target, before.target)
 assert.equal((await camera()).yaw, before.yaw)
 assert.equal(await page.getByTestId('space-view').getAttribute('data-map-selections'), '0')
 const prePinch = await camera()
 await touch('touchStart', [contact(1, 130, 310), contact(2, 230, 310)])
 await touch('touchMove', [contact(1, 90, 310), contact(2, 270, 310)])
 await touch('touchEnd', [])
 assert.ok((await camera()).distance < prePinch.distance)
 assert.equal(await page.getByTestId('space-view').getAttribute('data-map-selections'), '0')
 await touch('touchStart', [contact(1, 190, 310)])
 await touch('touchCancel', [])
 await page.touchscreen.tap(190, 310)
 assert.equal(await page.getByTestId('space-view').getAttribute('data-map-selections'), '1')
 await page.getByTestId('camera-recenter').tap()
 const planet = await page.getByTestId('body-hit-touch-planet').boundingBox()
 assert.ok(planet)
 await page.touchscreen.tap(planet.x + planet.width / 2, planet.y + planet.height / 2)
 assert.equal(await page.getByTestId('space-view').getAttribute('data-map-selections'), '2')
 console.log('PASS trusted Chromium touch: one-finger pan, pinch zoom, cancellation, empty/body taps, fallback recenter')
 for (const size of [{width:390,height:844},{width:375,height:667},{width:844,height:390},{width:390,height:600},{width:390,height:844}]) {
   await page.setViewportSize(size)
   await page.getByRole('button', {name:'HUD menu',exact:true}).tap()
   await page.getByRole('button', {name:'Console',exact:true}).tap()
   await page.getByLabel('Console draft').fill('retained touch draft')
   await page.getByRole('button', {name:'Objects',exact:true}).tap()
   await page.getByRole('button', {name:'Console',exact:true}).tap()
   assert.equal(await page.getByLabel('Console draft').inputValue(), 'retained touch draft')
   const box = await page.getByRole('dialog', {name:'Console panel',exact:true}).boundingBox()
   assert.ok(Math.abs(box.x)<1 && Math.abs(box.y)<1 && Math.abs(box.width-size.width)<1 && Math.abs(box.height-size.height)<1, JSON.stringify(box))
   await page.getByRole('button', {name:'Close Console panel',exact:true}).tap()
   const state = await page.evaluate(() => {
      const view=document.querySelector('[data-testid="space-view"]')
      return { width:document.documentElement.scrollWidth, viewport:innerWidth, inert:!!view.querySelector('[data-testid="space-canvas-region"]').closest('[inert]'), hit:document.elementFromPoint(innerWidth/2,innerHeight/2)?.closest('[data-testid="space-canvas-region"]')!==null, rootScroll:[view.scrollTop,view.scrollLeft], controls:[...document.querySelectorAll('[data-testid="space-camera-controls"] button, [data-testid="floating-nav"] a, [data-testid="floating-nav"] button')].filter(e=>e.getClientRects().length && getComputedStyle(e).visibility!=='hidden').map(e=>{const r=e.getBoundingClientRect();const hit=document.elementFromPoint(r.x+r.width/2,r.y+r.height/2);return {label:e.getAttribute('aria-label')||e.textContent,rect:{x:r.x,y:r.y,width:r.width,height:r.height},hit:hit===e||e.contains(hit), blocker:hit?.outerHTML.slice(0,250)}})}
   })
   assert.equal(state.width,state.viewport)
   assert.equal(state.inert,false)
   assert.equal(state.hit,true)
   assert.deepEqual(state.rootScroll,[0,0])
   for(const c of state.controls){assert.ok(c.rect.x>=0 && c.rect.x+c.rect.width<=size.width+1 && c.rect.y>=0 && c.rect.y+c.rect.height<=size.height+1,JSON.stringify(c));assert.ok(c.hit,JSON.stringify(c))}
   await page.getByRole('button',{name:'HUD menu',exact:true}).tap()
   await page.getByRole('button',{name:'Arrange HUD',exact:true}).tap()
   await page.getByRole('button',{name:'Close HUD settings',exact:true}).tap()
   assert.equal(await region.evaluate(e=>!!e.closest('[inert]')),false)
   const afterClose = await camera()
   await touch('touchStart', [contact(1,size.width/2,size.height/2)])
   await touch('touchMove', [contact(1,size.width/2+30,size.height/2+20)])
   await touch('touchEnd', [])
   assert.notDeepEqual((await camera()).target,afterClose.target)
   await page.getByTestId('camera-recenter').tap()
   await page.screenshot({path:path.join(output,`map-${size.width}x${size.height}.png`)})
   console.log('PASS touch open/switch/close/settings, hit targets, no scroll/overflow after resize',JSON.stringify(size))
 }
 await page.setViewportSize({width:1440,height:900})
 assert.equal(await page.getByRole('dialog').count(),0)
 assert.equal(await page.getByRole('button',{name:'HUD menu',exact:true}).isVisible(),false)
 for(const label of ['Objects','Command','Console']) assert.equal(await page.getByRole('region',{name:`${label} panel`,exact:true}).isVisible(),true)
 const mouseBefore=await camera()
 await page.mouse.move(700,400);await page.mouse.down();await page.mouse.move(750,430,{steps:4});await page.mouse.up()
 assert.notEqual((await camera()).yaw,mouseBefore.yaw)
 await page.screenshot({path:path.join(output,'desktop-map.png')})
 console.log('PASS desktop docks and mouse orbit after mobile-to-desktop resize')
 await context.close()
 } finally { await browser.close() }
 const executablePath='/Users/travis/Library/Caches/ms-playwright/webkit-2182/pw_run.sh'
 if(fs.existsSync(executablePath)) {
   let b
   try { b=await webkit.launch({headless:true,executablePath});const p=await b.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});await p.goto(url);await p.getByRole('button',{name:'HUD menu',exact:true}).tap();await p.getByRole('button',{name:'Objects',exact:true}).tap();await p.getByRole('button',{name:'Close Objects panel',exact:true}).tap();assert.equal(await p.getByTestId('space-canvas-region').evaluate(e=>!!e.closest('[inert]')),false);await p.waitForFunction(()=>!!document.querySelector('[data-testid="space-camera-controls"]'));const region=p.getByTestId('space-canvas-region');const before=JSON.parse(await region.getAttribute('data-camera'));await p.getByTestId('camera-zoom-in').tap();assert.ok(JSON.parse(await region.getAttribute('data-camera')).distance<before.distance);await p.touchscreen.tap(190,310);assert.equal(await p.getByTestId('space-view').getAttribute('data-map-selections'),'1');await p.screenshot({path:path.join(output,'webkit-map.png')});console.log('PASS installed WebKit mobile touch open/close, restored map input, tap selection and zoom fallback') }
   catch(e){console.log('WEBKIT LIMITATION:',e.message.split('\n')[0])}
   finally {await b?.close()}
 }
})().catch(e=>{console.error(e);process.exitCode=1})
