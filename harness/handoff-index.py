#!/usr/bin/env python3
"""Index a large handoff so delegations page it instead of reading it whole.

`openspec-rulings-index.py` already does this for one file per change. Every
other handoff is still read end to end by every delegation that touches it —
`*-impl-contract.md` runs 48 KB, `*-analysis.md` 30 KB, a panel report 25 KB, an
adversary round 29 KB, and the implementation crew alone opens four of them.

The mechanism is lifted from ObservationPack in NVlabs/SoL-Pi (MIT): a large
body is replaced, for every reader after the first, by a short stable handle
that carries enough of the original to decide with — head and tail excerpts on
**whole lines**, the real byte/line/token cost, a map of what is inside — plus
**the exact command that pages the rest back**. A handle nobody is told how to
open is a handle nobody opens; that is why the impl-contract's hand-written
`## Reading list` works and no other file has one.

    handoff-index.py docs/handoffs/<id>-impl-contract.md
    handoff-index.py --all                   # every oversized handoff
    handoff-index.py --check <path>          # exit 1 when the index is stale
    handoff-index.py --all --dry-run         # what would be indexed, and the saving

Who reads what:

**The agent authoring the file reads it whole.** So does the one revising it —
you cannot rewrite current state through a keyhole. This is SoL-Pi's
`FULL_SENDS`: the first readers pay full price because they are the ones who
need every byte.

**Every downstream delegation is handed the index path instead**, and opens the
ranges it needs. An orchestrator naming `<id>-impl-contract-index.md` in a
delegation is doing the same thing as naming `<id>-rulings-index.md` today.

Files at or below --threshold (default 10 KB) are left alone: a handle costs
more than they do. `*-rulings.md` belongs to `openspec-rulings-index.py` and is
skipped here so one file never has two indexes.
"""
import argparse, pathlib, re, sys

THRESHOLD_BYTES = 10 * 1024
# Split evenly between head and tail, whole lines only.
EXCERPT_BYTES = 1024
CHARS_PER_TOKEN = 4

HEADING = re.compile(r"^(?P<hashes>#{2,4})\s+(?P<text>.+?)\s*$")
SEVERITY = re.compile(r"\b(BLOCKER|MAJOR|MINOR)\b")
FENCE = re.compile(r"^\s*(```|~~~)")
# Owned by another generator, generated by this one, or already a reduction.
# A file is reduced or it is indexed, never both: `check-quote-fidelity.py`
# already governs a reduction, and the hook branch that governs it does not
# check index staleness, so an index beside one could rot unnoticed.
SKIP = ("-rulings.md", "-index.md", "-consolidated.md", "-reduced.md", "README.md")
SKIP_WHY = {"-rulings.md": "owned by openspec-rulings-index.py",
            "-index.md": "generated by this script",
            "-consolidated.md": "already a reduction — governed by check-quote-fidelity.py",
            "-reduced.md": "already a reduction — governed by check-quote-fidelity.py",
            "README.md": "not a handoff"}


def estimate_tokens(text):
    return -(-len(text) // CHARS_PER_TOKEN)


def excerpt(lines, budget, from_end):
    """Whole lines from one end, up to `budget` bytes. Never a mid-line cut.

    A truncated last line reads as corrupted evidence rather than as an
    excerpt, and an agent that cannot tell the two apart will page the whole
    file back to find out which it was.
    """
    picked, used = [], 0
    for line in (reversed(lines) if from_end else lines):
        size = len(line.encode()) + 1
        if used + size > budget:
            break
        picked.append(line)
        used += size
    return list(reversed(picked)) if from_end else picked


def sections(text):
    """-> [{level, text, line, end, gist}] for every heading, fences ignored.

    A `## Example` inside a fenced code block is sample output, not a section;
    indexing it points a reader at a line range that does not exist as prose.
    """
    lines = text.split("\n")
    out, fenced = [], False
    for n, line in enumerate(lines, start=1):
        if FENCE.match(line):
            fenced = not fenced
            continue
        if fenced:
            continue
        m = HEADING.match(line)
        if not m:
            continue
        if out:
            out[-1]["end"] = n - 1
        out.append(dict(level=len(m.group("hashes")), text=m.group("text").strip(),
                        line=n, end=len(lines), gist=""))
    for s in out:
        for line in lines[s["line"]:s["end"]]:
            stripped = line.strip()
            if stripped and not stripped.startswith("#") and not FENCE.match(line):
                s["gist"] = stripped
                break
    return out


def fence_for(lines):
    """A fence longer than any backtick run inside the excerpt.

    Handoffs are full of fenced code, and an excerpt that lands on an opening
    ``` would otherwise close the wrapper early and spill the rest of the index
    into a code block.
    """
    longest = max((len(m) for line in lines for m in re.findall(r"`+", line)), default=0)
    return "`" * max(3, longest + 1)


def cell(text, width=88):
    text = re.sub(r"\s+", " ", text).replace("|", "\\|").strip()
    return text[: width - 1] + "…" if len(text) > width else text


def render(src, rel, text):
    lines = text.split("\n")
    body = sections(text)
    half = EXCERPT_BYTES // 2
    head = excerpt(lines, half, False)
    tail = excerpt(lines, EXCERPT_BYTES - half, True)
    severities = sum(1 for s in body if SEVERITY.search(s["text"]))

    out = [f"# {src.stem} — handoff index",
           "",
           f"Generated by `harness/handoff-index.py {rel}` from `{src.name}` "
           f"({len(text.encode()):,} bytes, {len(lines):,} lines, ~{estimate_tokens(text):,} tokens, "
           f"{len(body)} sections).",
           "",
           "**Read this file instead of that one** unless you are writing or revising it —",
           "the author needs every byte, a downstream delegation needs the two sections that",
           "bear on its task. Open any row by its line range:",
           "",
           "```bash",
           f"sed -n '<start>,<end>p' {rel}",
           "```",
           ""]
    if severities:
        out += [f"{severities} of the {len(body)} sections carry a severity. "
                "An index line is not a finding — quote from the source, never from here.",
                ""]
    out += ["| Section | Lines | Bytes | Opens with |",
            "| --- | --- | --- | --- |"]
    for s in body:
        span = "\n".join(lines[s["line"] - 1: s["end"]])
        label = ("↳ " * (s["level"] - 2)) + cell(s["text"])
        out.append(f"| {label} | {s['line']}-{s['end']} | {len(span.encode()):,} | "
                   f"{cell(s['gist'], 70) or '—'} |")
    if not body:
        out += [f"| _(no headings — this file has no internal structure to index)_ "
                f"| 1-{len(lines)} | {len(text.encode()):,} | {cell(next((l for l in lines if l.strip()), ''), 70)} |"]

    hf, tf = fence_for(head), fence_for(tail)
    out += ["", f"## First {len(head)} lines", "", hf, *head, hf, "",
            f"## Last {len(tail)} lines", "", tf, *tail, tf, "",
            f"_{len(text.encode()) - sum(len(l.encode()) + 1 for l in head + tail):,} bytes between them "
            f"are omitted here and unchanged in the source; page them with the ranges above._"]
    return "\n".join(out) + "\n"


def index_path(src):
    return src.with_name(f"{src.stem}-index.md")


def candidates(paths, all_of, handoffs, threshold):
    if paths:
        return [pathlib.Path(p) for p in paths]
    if not all_of:
        return []
    return sorted(p for p in handoffs.glob("*.md")
                  if not any(p.name.endswith(s) for s in SKIP)
                  and p.stat().st_size > threshold)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("path", nargs="*", help="handoff file(s) to index")
    ap.add_argument("--all", action="store_true", help="every oversized handoff in the handoffs dir")
    ap.add_argument("--check", action="store_true", help="verify indexes are current; exit 1 if not")
    ap.add_argument("--dry-run", action="store_true", help="report what would be written, write nothing")
    ap.add_argument("--threshold", type=int, default=THRESHOLD_BYTES, metavar="BYTES",
                    help=f"leave files this size or smaller alone (default {THRESHOLD_BYTES})")
    ap.add_argument("--handoffs", default="docs/handoffs", metavar="DIR",
                    help="handoffs directory for --all (default docs/handoffs)")
    args = ap.parse_args()

    repo = pathlib.Path.cwd()
    targets = candidates(args.path, args.all, pathlib.Path(args.handoffs), args.threshold)
    if not targets:
        if args.all:
            print(f"no handoff over {args.threshold:,} B in {args.handoffs}/ — nothing to index")
            return 0
        ap.error("name a handoff file, or pass --all")

    stale, wrote, skipped, saved = [], 0, 0, 0
    for src in targets:
        if not src.is_file():
            print(f"no such file: {src}", file=sys.stderr)
            return 2
        why = next((SKIP_WHY[s] for s in SKIP if src.name.endswith(s)), None)
        if why:
            print(f"{src}: skipped — {why}")
            skipped += 1
            continue
        text = src.read_text(errors="ignore")
        if len(text.encode()) <= args.threshold and not args.path:
            skipped += 1
            continue

        rel = src.relative_to(repo) if src.is_absolute() and src.is_relative_to(repo) else src
        want = render(src, rel, text)
        dst = index_path(src)
        have = dst.read_text(errors="ignore") if dst.exists() else None
        delta = len(text.encode()) - len(want.encode())
        saved += max(0, delta)

        if args.check:
            if have != want:
                stale.append(src)
                print(f"{dst}: stale — run `harness/handoff-index.py {rel}`", file=sys.stderr)
            else:
                print(f"{dst}: current")
            continue
        if args.dry_run:
            print(f"{rel}: {len(text.encode()):,} B -> {len(want.encode()):,} B  "
                  f"(saves ~{estimate_tokens(text) - estimate_tokens(want):,} tokens per downstream read)")
            continue
        if have != want:
            dst.write_text(want)
            wrote += 1
        print(f"{rel}: {len(text.encode()):,} B -> {len(want.encode()):,} B  {dst}")

    if args.check:
        return 1 if stale else 0
    if not args.dry_run:
        print(f"\n{wrote} index file(s) written, {len(targets) - wrote - skipped} already current, "
              f"{skipped} skipped")
    print(f"~{saved // CHARS_PER_TOKEN:,} tokens saved per delegation that reads the indexes "
          f"instead of the sources")
    return 0


if __name__ == "__main__":
    sys.exit(main())
